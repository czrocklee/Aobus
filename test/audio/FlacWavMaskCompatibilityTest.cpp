    void checkReferenceInfo(DecodedStreamInfo const& info,
                            AudioCodec codec,
                            ChannelLayoutOrigin origin,
                            std::uint32_t mask = 3)
    {
      CHECK(info.sourceFormat == SignalFormat{.sampleRate = 48000,
                                              .channels = 2,
                                              .precisionBits = 16,
                                              .sampleKind = SampleKind::Integer,
                                              .speakerMask = mask});
      CHECK(info.outputFormat ==
            PcmFormat{.sampleRate = 48000, .channels = 2, .encoding = SampleEncoding::Signed16Le, .speakerMask = mask});
      CHECK(info.sourceChannelLayout.origin == origin);
      CHECK(info.optTotalFrames == 48U);
      CHECK(info.duration == std::chrono::milliseconds{1});
      CHECK(info.codec == codec);
      CHECK_FALSE(info.isLossy);
    }

    void checkReferencePcm(DecoderSession& decoder, std::span<std::uint8_t const> expected)
    {
      auto const info = decoder.streamInfo();
      REQUIRE(expected.size() == 192U);
      std::size_t framesRead = 0;

      // Reference FLAC block sizes need not match the 16-frame marker runs.
      while (framesRead < 48U)
      {
        auto const blockRes = decoder.readNextBlock();
        REQUIRE(blockRes);
        auto const& block = *blockRes;
        CHECK(block.firstFrameIndex == framesRead);
        REQUIRE(block.frames > 0U);
        REQUIRE(block.frames <= 48U - framesRead);
        REQUIRE(block.bytes.size() == static_cast<std::size_t>(block.frames) * 4U);

        for (std::size_t byteIndex = 0; byteIndex < block.bytes.size(); ++byteIndex)
        {
          CAPTURE(framesRead, byteIndex);
          CHECK(std::to_integer<std::uint8_t>(block.bytes[byteIndex]) == expected[(framesRead * 4U) + byteIndex]);
        }

        framesRead += block.frames;

        if (block.endOfStream)
        {
          CHECK(framesRead == 48U);
        }

        CHECK(decoder.streamInfo() == info);
      }

      CHECK(framesRead == 48U);

      for (std::size_t repeat = 0; repeat < 3U; ++repeat)
      {
        auto const endRes = decoder.readNextBlock();
        REQUIRE(endRes);
        CHECK(endRes->endOfStream);
        CHECK(endRes->frames == 0U);
        CHECK(endRes->bytes.empty());
        CHECK(decoder.streamInfo() == info);
      }
    }
