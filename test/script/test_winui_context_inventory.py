"""Consistency between the WinUI lint-context aggregate and the Python query inventory.

The explicit project list in ``app/windows-winui/CMakeLists.txt`` and the
queryable-project inventory in ``ao.core.winuitidy`` are two spellings of one
contract: every project the Python side can query must be generated by the
aggregate, and the aggregate must stay generation-only. This is a portable
text contract test; it runs no CMake and parses only the fixed aggregate block.
"""

import unittest
from pathlib import Path

from ao.core import winuitidy
from ao.core.paths import PROJECT_ROOT

CMAKE_LISTS = PROJECT_ROOT / "app" / "windows-winui" / "CMakeLists.txt"
WINUITIDY_MODULE = PROJECT_ROOT / "script" / "ao" / "core" / "winuitidy.py"

LIBRARY_PROJECT = "aobus-winui-lib"
PRODUCT_TARGET = "aobus-winui"

# The aggregate's fixed generation-only context: one MSBuild invocation at a
# time, no project-reference builds, and the lint-context preparation target.
REQUIRED_CONTEXT_FLAGS = (
    "/m:1",
    "/p:BuildProjectReferences=false",
    "/t:AobusPrepareLintContext",
)


def aggregate_block(text: str) -> str:
    """Return the ``foreach(_project IN ITEMS ...)`` block of the lint-context aggregate."""
    start = text.index("foreach(_project IN ITEMS")
    end = text.index("endforeach()", start)
    return text[start:end]


def aggregate_projects(block: str) -> list[str]:
    """Return the explicit project names from the aggregate's item list."""
    head, _, _body = block.partition(")")
    return head.partition("IN ITEMS")[2].split()


class WinUiContextInventoryTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.block = aggregate_block(CMAKE_LISTS.read_text(encoding="utf-8"))
        cls.projects = aggregate_projects(cls.block)

    def test_the_aggregate_covers_exactly_the_library_and_every_queryable_project(self):
        # Set equality, not order: a future queryable project without a
        # matching generation entry (or a generated project the Python side
        # can never query) fails here.
        auxiliary = set(self.projects[1:])
        queried = {Path(project).stem for project in winuitidy._AUXILIARY_SOURCE_PROJECTS.values()}
        self.assertEqual(auxiliary, queried)

    def test_the_library_project_is_generated_first(self):
        # The library context must exist before the probe projections that
        # consume its WinMD and generated headers.
        self.assertEqual(self.projects[0], LIBRARY_PROJECT)
        self.assertEqual(len(self.projects), len(set(self.projects)))

    def test_the_library_project_is_queried_by_the_python_module(self):
        source = WINUITIDY_MODULE.read_text(encoding="utf-8")
        self.assertIn(f"{LIBRARY_PROJECT}.vcxproj", source)

    def test_the_aggregate_stays_generation_only_and_never_builds_the_product(self):
        self.assertNotIn(PRODUCT_TARGET, self.projects)
        for flag in REQUIRED_CONTEXT_FLAGS:
            self.assertIn(flag, self.block)

    def test_auxiliary_project_paths_live_in_the_winui_directory(self):
        # The Python inventory paths are relative to the same CMake directory
        # whose per-project ``${_project}.vcxproj`` the aggregate generates.
        for project in winuitidy._AUXILIARY_SOURCE_PROJECTS.values():
            path = Path(project)
            self.assertEqual(path.parent.as_posix(), "app/windows-winui")
            self.assertEqual(path.suffix, ".vcxproj")


if __name__ == "__main__":
    unittest.main()
